type AttackCondition struct {
	SDO            `json:",inline"`
	OnTrueRefs     []string `json:"on_true_refs"`
	OnFalseRefs    []string `json:"on_false_refs"`
	Pattern        string   `json:"pattern"`
	PatternType    string   `json:"pattern_type"`
	PatternVersion string   `json:"pattern_version"`
}

var _ AttackFlowObject = (*AttackCondition)(nil)

func (op AttackCondition) Append(obj AttackFlowObject) AttackFlowObject {
	// TODO: properly introduce branching condition
	op.OnTrueRefs = append(op.OnTrueRefs, obj.GetID())
	return op
}

